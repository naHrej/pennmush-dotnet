    public static bool TryResolve(string typed, out string canonical)
    {
        string name = typed.ToUpperInvariant();
        if (name.Length == 0)
        {
            canonical = string.Empty;
            return false;
        }

        if (ByName.TryGetValue(name, out var exact))
        {
            canonical = exact.Name;
            return true;
        }

        string? match = null;
        foreach (var key in PrefixKeys)
        {
            if (!key.Key.StartsWith(name, StringComparison.Ordinal))
                continue;
            if (match == null)
                match = key.Canonical;
            else if (!string.Equals(match, key.Canonical, StringComparison.Ordinal))
            {
                canonical = string.Empty;
                return false;
            }
        }

        if (match == null)
        {
            canonical = string.Empty;
            return false;
        }

        canonical = match;
        return true;
    }

    public static AttributeFlags DefaultFlags(string canonical)
    {
        return ByName.TryGetValue(canonical, out var found) ? found.Flags : AttributeFlags.None;
    }
