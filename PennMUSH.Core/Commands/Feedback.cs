    private static readonly Dictionary<Feedback, string> Overrides = new();

    /// <summary>
    /// Replace the sentence for this server. Tokens in the new sentence
    /// still use {{name}} and are filled by <see cref="Text"/>.
    /// </summary>
    public static void SetTemplate(Feedback message, string template)
    {
        ArgumentNullException.ThrowIfNull(template);
        Overrides[message] = template;
    }

    public static void ResetTemplates() => Overrides.Clear();

    /// <summary>
    /// The sentence for this reply. Each {{token}} needs a name and value.
    /// </summary>
    public static string Text(this Feedback message, string name, string value)
        => message.Text((name, value));

    public static string Text(this Feedback message, params (string Name, string Value)[] tokens)
    {
        if (!Overrides.TryGetValue(message, out var text) && !Defaults.TryGetValue(message, out text))
            throw new ArgumentOutOfRangeException(nameof(message), message, "No template for this reply.");

        var used = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (name, value) in tokens)
        {
            if (string.IsNullOrEmpty(name) || !used.Add(name))
                throw new ArgumentException($"Token '{name}' is missing or repeated.", nameof(tokens));

            var marker = "{{" + name + "}}";
            if (!text.Contains(marker, StringComparison.Ordinal))
                throw new ArgumentException($"Feedback.{message} has no {marker} token.", nameof(tokens));

            text = text.Replace(marker, value ?? string.Empty, StringComparison.Ordinal);
        }

        var open = text.IndexOf("{{", StringComparison.Ordinal);
        if (open >= 0)
        {
            var close = text.IndexOf("}}", open, StringComparison.Ordinal);
            var missing = close > open ? text.Substring(open, close - open + 2) : "{{";
            throw new ArgumentException($"Feedback.{message} still contains {missing}.", nameof(tokens));
        }

        return text;
    }
