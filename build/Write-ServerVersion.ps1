param(
    [Parameter(Mandatory = $true)][string] $RepoRoot,
    [Parameter(Mandatory = $true)][string] $SourcePath,
    [Parameter(Mandatory = $true)][string] $ProductPath,
    [Parameter(Mandatory = $true)][string] $InformationalPath
)

$ErrorActionPreference = "Stop"
$major = 0
$minor = 1
$build = 0
$commit = ""

function Invoke-Git {
    param([string[]] $GitArgs)
    & git -C $RepoRoot @GitArgs
    if ($LASTEXITCODE -ne 0) {
        throw "git $($GitArgs -join ' ') failed"
    }
}

try {
    $head = (Invoke-Git @("rev-parse", "HEAD")).Trim()
    $short = (Invoke-Git @("rev-parse", "--short=7", "HEAD")).Trim()
    $log = Invoke-Git @("log", "--format=%H%x09%s")
    $best = 0
    $bestCommit = ""
    foreach ($line in $log) {
        $split = $line.IndexOf("`t")
        if ($split -lt 0) { continue }
        $hash = $line.Substring(0, $split).Trim()
        $subject = $line.Substring($split + 1)
        $number = 0
        if ($subject -match "Merge pull request #(\d+)\b") {
            $number = [int]$Matches[1]
        }
        elseif ($subject -match "\(#(\d+)\)\s*$") {
            $number = [int]$Matches[1]
        }
        if ($number -gt $best) {
            $best = $number
            $bestCommit = $hash
        }
    }

    $build = $best
    if ($bestCommit.Length -gt 0 -and $head -ne $bestCommit) {
        $commit = $short
    }
}
catch {
    $build = 0
    $commit = ""
}

$product = "$major.$minor.$build"
$informational = if ($commit.Length -eq 0) { $product } else { "$product+g$commit" }
$commitLiteral = $commit.Replace("\", "\\").Replace('"', '\"')
$source = @"
// Generated by build/Write-ServerVersion.ps1. Do not edit.
namespace PennMUSH.Core;

public static class ServerVersion
{
    public const int Major = $major;
    public const int Minor = $minor;
    public const int Build = $build;
    public const string Commit = "$commitLiteral";
    public const string Text = "$informational";
}
"@

$utf8 = New-Object System.Text.UTF8Encoding $false
foreach ($path in @($SourcePath, $ProductPath, $InformationalPath)) {
    $directory = Split-Path -Parent $path
    if (-not [string]::IsNullOrEmpty($directory)) {
        New-Item -ItemType Directory -Force -Path $directory | Out-Null
    }
}

[System.IO.File]::WriteAllText($SourcePath, $source, $utf8)
[System.IO.File]::WriteAllText($ProductPath, $product, $utf8)
[System.IO.File]::WriteAllText($InformationalPath, $informational, $utf8)
