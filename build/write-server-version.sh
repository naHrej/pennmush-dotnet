#!/usr/bin/env bash
set -euo pipefail

if [ "$#" -ne 4 ]; then
    echo "Usage: $0 <repo-root> <source-path> <product-path> <informational-path>" >&2
    exit 1
fi

REPO_ROOT="$1"
SOURCE_PATH="$2"
PRODUCT_PATH="$3"
INFORMATIONAL_PATH="$4"

MAJOR=0
MINOR=1
BUILD=0
COMMIT=""

if HEAD_HASH=$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null) && \
   SHORT_HASH=$(git -C "$REPO_ROOT" rev-parse --short=7 HEAD 2>/dev/null); then
    BEST=0
    BEST_COMMIT=""
    while IFS=$'\t' read -r HASH SUBJECT; do
        [ -z "$HASH" ] && continue
        NUMBER=0
        if [[ "$SUBJECT" =~ Merge\ pull\ request\ #([0-9]+)([^0-9]|$) ]]; then
            NUMBER="${BASH_REMATCH[1]}"
        elif [[ "$SUBJECT" =~ \(#([0-9]+)\)[[:space:]]*$ ]]; then
            NUMBER="${BASH_REMATCH[1]}"
        fi
        if [ "$NUMBER" -gt "$BEST" ]; then
            BEST="$NUMBER"
            BEST_COMMIT="$HASH"
        fi
    done < <(git -C "$REPO_ROOT" log --format="%H%x09%s" 2>/dev/null || true)

    BUILD="$BEST"
    if [ -n "$BEST_COMMIT" ] && [ "$HEAD_HASH" != "$BEST_COMMIT" ]; then
        COMMIT="$SHORT_HASH"
    fi
fi

PRODUCT="${MAJOR}.${MINOR}.${BUILD}"
if [ -z "$COMMIT" ]; then
    INFORMATIONAL="$PRODUCT"
else
    INFORMATIONAL="${PRODUCT}+g${COMMIT}"
fi

COMMIT_LITERAL="${COMMIT//\\/\\\\}"
COMMIT_LITERAL="${COMMIT_LITERAL//\"/\\\"}"

for OUT_PATH in "$SOURCE_PATH" "$PRODUCT_PATH" "$INFORMATIONAL_PATH"; do
    OUT_DIR="$(dirname "$OUT_PATH")"
    if [ -n "$OUT_DIR" ]; then
        mkdir -p "$OUT_DIR"
    fi
done

cat > "$SOURCE_PATH" <<EOF
// Generated by build/write-server-version.sh. Do not edit.
namespace PennMUSH.Core;

public static class ServerVersion
{
    public const int Major = $MAJOR;
    public const int Minor = $MINOR;
    public const int Build = $BUILD;
    public const string Commit = "$COMMIT_LITERAL";
    public const string Text = "$INFORMATIONAL";
}
EOF

printf '%s' "$PRODUCT" > "$PRODUCT_PATH"
printf '%s' "$INFORMATIONAL" > "$INFORMATIONAL_PATH"
